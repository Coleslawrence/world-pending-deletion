// Builds the System's reserve builds for the Entrant pool (js/content/pool.js).
//   node tools/pool-seed.js            write js/content/pool.js (30 builds for each of rounds 1 to 7)
//   node tools/pool-seed.js --check    only check that the file's pieces, Gifts and Titles still exist
// Each reserve is a bot's build as it walked into that round's fight, after shopping. The bot builds around each
// archetype in turn, so every round's 30 builds spread across all of them. Runs are seeded, so the file is repeatable.
// Rerun this after big changes to skills, gear or the shop, so reserves stay close to what a player has at each round.
'use strict';
const fs = require('fs'), path = require('path');
const G = require('../js/core.js'); const B = require('./bot.js');

const OUT = path.join(__dirname, '..', 'js', 'content', 'pool.js');
const SIZE = G.POOL_SIZE, ROUNDS = G.POOL_ROUNDS;

function check() {
  const bad = [];
  G.POOL_SEED.forEach((list, r) => list.forEach((b, i) => {
    const at = `round ${r + 1} build ${i + 1}`;
    if (!G.ARCH[b.p] && b.p) bad.push(`${at}: unknown path ${b.p}`);
    (b.b || []).forEach(([id]) => { if (!G.SKILLS[id]) bad.push(`${at}: unknown skill ${id}`); });
    (b.e || []).forEach(([id]) => { if (!G.GEAR[id]) bad.push(`${at}: unknown gear ${id}`); });
    (b.g || []).forEach(id => { if (!G.GIFTS[id]) bad.push(`${at}: unknown Gift ${id}`); });
    if (b.t && !G.TITLES[b.t]) bad.push(`${at}: unknown Title ${b.t}`);
  }));
  if (G.POOL_SEED.length !== ROUNDS) bad.push(`expected ${ROUNDS} rounds, found ${G.POOL_SEED.length}`);
  G.POOL_SEED.forEach((list, r) => { if (list.length !== SIZE) bad.push(`round ${r + 1}: expected ${SIZE} builds, found ${list.length}`); });
  return bad;
}
if (process.argv.includes('--check')) {
  const bad = check();
  bad.forEach(b => console.log('✗ ' + b));
  console.log(bad.length ? `${bad.length} problem(s) in js/content/pool.js. Rerun node tools/pool-seed.js.` : `✓ pool reserves: ${ROUNDS} rounds × ${SIZE} builds, all pieces known`);
  process.exit(bad.length ? 1 : 0);
}

// The game and the bot both draw from Math.random, so seeding it makes the file repeatable
let s = 20261101;
Math.random = () => { s |= 0; s = s + 0x6D2B79F5 | 0; let t = Math.imul(s ^ s >>> 15, 1 | s); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; };
G.POOL.off = true; // reserves come from runs that never met the pool

// The compact form pool.js stores: n name, w world, wt world type, p path, l level, hp max HP, s stats (STATS order),
// g Gifts, t Title, m stat milestones, h Hidden Path, b skill bar [id, star, mods], e gear [id, star]
function compact(run) {
  const x = G.poolSnap(run);
  const o = { n: run.name, w: x.worldName, wt: x.worldType, p: x.path || undefined, l: x.level, hp: x.maxHp, s: G.STATS.map(k => x.stats[k]), g: x.gifts.length ? x.gifts : undefined,
    t: x.title || undefined, m: Object.keys(x.milestones || {}).filter(k => x.milestones[k]), h: x.hiddenPath || undefined,
    b: x.bar.map(p => p.mods.length ? [p.id, p.star, p.mods] : [p.id, p.star]), e: x.gear.map(p => [p.id, p.star]) };
  if (!o.m.length) delete o.m;
  return o;
}
const out = Array.from({ length: ROUNDS }, () => []);
const mains = G.ARCH_KEYS.slice();
let runs = 0;
while (out.some(l => l.length < SIZE) && runs < 2000) {
  const main = mains[runs % mains.length]; runs++;
  const meta = G.newMeta(); delete meta.rank;
  mains.forEach(k => meta.unlocks['arch_' + k] = true);
  const taken = {};
  B.playRun(meta, false, { main, noElite: true, snap: (stage, run) => {
    if (stage !== 'shop' || run.elite || run.round > ROUNDS || taken[run.round]) return;
    taken[run.round] = true;
    // Rename the bot to a champion of its world, as a player would be
    run.name = G.pick(G.WORLD_TYPES[run.world.type].champs);
    const l = out[run.round - 1];
    if (l.length < SIZE) l.push(compact(run));
  } });
}
if (out.some(l => l.length < SIZE)) throw new Error('not enough bot runs reached every round: ' + out.map(l => l.length).join(', '));

const lines = out.map((l, i) => `  // Round ${i + 1}\n  [\n${l.map(b => '    ' + JSON.stringify(b) + ',').join('\n')}\n  ],`).join('\n');
fs.writeFileSync(OUT, `// ===== [World Pending Deletion] — content: the Entrant pool's reserve builds =====
// The Entrant pool holds ${SIZE} builds for each of rounds 1 to ${ROUNDS} (see "Entrant pool" in js/core.js). Players' own builds
// replace these as they play; until then, a slot nobody has filled holds the System's reserve from this list.
// Generated by node tools/pool-seed.js from bot runs: don't edit by hand, rerun the tool after big content changes.
// n name, w world, wt world type, p path, l level, hp max HP, s stats (${G.STATS.join(' ')}), g Gifts, t Title,
// m stat milestones, h Hidden Path, b skill bar [id, star, mods], e gear [id, star]
'use strict';
const POOL_SEED = [
${lines}
];
`);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${ROUNDS} rounds × ${SIZE} builds from ${runs} bot runs, ${fs.statSync(OUT).size} bytes`);
